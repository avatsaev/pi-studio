pub const APP: Hello<'static> = Hello { client_id: "client-1", app_version: "pistudiodesktop/test" };

/// Bytes that are not periodic within a chunk, the same for the same `len`.
pub fn pattern(len: usize) -> Vec<u8> {
    (0..len).map(byte_at).collect()
}

pub fn byte_at(index: usize) -> u8 {
    u8::try_from((index * 31 + index / 251) % 256).unwrap_or(0)
}

/// A connection to the stand-in over a real socket.
pub async fn connect(daemon: &StandInDaemon, limits: Limits) -> Connection {
    let socket = dial(&daemon.url(), None, Duration::from_secs(5), limits.max_message_bytes).await.expect("the stand-in accepts the dial");
    Connection::open(socket, &APP, limits).await.expect("the handshake succeeds")
}

/// Waits, in real time, until `done`; a test that waits more than ten seconds has failed.
pub async fn eventually(what: &str, mut done: impl FnMut() -> bool) {
    let start = Instant::now();
    while !done() {
        assert!(start.elapsed() < Duration::from_secs(10), "{what} did not happen within ten seconds");
        tokio::time::sleep(Duration::from_millis(5)).await;
    }
}

/// A cancel that a test fires: `cancelled()` completes after `cancel()`, once or before it is awaited.
#[derive(Clone, Default)]
pub struct Trigger(Arc<Notify>);

impl Trigger {
    pub fn cancel(&self) {
        self.0.notify_one();
    }

    pub async fn cancelled(self) {
        self.0.notified().await;
    }
}

/// A source of `len` generated bytes that counts how many were read, so that a test can see how far
/// ahead of the daemon the upload reads. It holds no bytes itself.
pub struct Generated {
    len: usize,
    at: usize,
    pub read: Arc<AtomicU64>,
}

impl Generated {
    pub fn new(len: usize) -> Self {
        Self { len, at: 0, read: Arc::new(AtomicU64::new(0)) }
    }
}

impl UploadSource for Generated {
    fn size(&self) -> Option<u64> {
        u64::try_from(self.len).ok()
    }

    async fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        let count = buf.len().min(self.len - self.at);
        for (offset, slot) in buf.iter_mut().take(count).enumerate() {
            *slot = byte_at(self.at + offset);
        }
        self.at += count;
        self.read.fetch_add(u64::try_from(count).unwrap_or(0), Ordering::SeqCst);
        Ok(count)
    }
}

/// A source that returns at most `most` bytes per read, as a socket or a slow disk might.
pub struct Trickle {
    pub data: Vec<u8>,
    pub at: usize,
    pub most: usize,
}

impl UploadSource for Trickle {
    fn size(&self) -> Option<u64> {
        u64::try_from(self.data.len()).ok()
    }

    async fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        let count = buf.len().min(self.most).min(self.data.len() - self.at);
        buf[..count].copy_from_slice(&self.data[self.at..self.at + count]);
        self.at += count;
        Ok(count)
    }
}

/// A source that reads `data` and then fails.
pub struct Failing {
    pub data: Vec<u8>,
    pub at: usize,
}

impl UploadSource for Failing {
    fn size(&self) -> Option<u64> {
        None
    }

    async fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        if self.at == self.data.len() {
            return Err(std::io::Error::from(std::io::ErrorKind::PermissionDenied));
        }
        let count = buf.len().min(self.data.len() - self.at);
        buf[..count].copy_from_slice(&self.data[self.at..self.at + count]);
        self.at += count;
        Ok(count)
    }
}

/// A source that gives more than it was given room for.
pub struct Overfull;

impl UploadSource for Overfull {
    fn size(&self) -> Option<u64> {
        None
    }

    async fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        Ok(buf.len() + 1)
    }
}

// ---- a scripted daemon over a pipe ----

type Pipe = WebSocketStream<DuplexStream>;

/// The daemon's end of a pipe, driven by the test.
pub struct Fake {
    ws: Pipe,
}

/// A connection over a pipe of `room` bytes each way, and the daemon at its other end, handshaken.
pub async fn fake_connection(limits: Limits, room: usize) -> (Connection, Fake) {
    let (client, daemon) = duplex(room);
    let config = WebSocketConfig::default().max_message_size(Some(limits.max_message_bytes)).max_frame_size(Some(limits.max_message_bytes));
    let client = WebSocketStream::from_raw_socket(client, Role::Client, Some(config)).await;
    let mut fake = Fake { ws: WebSocketStream::from_raw_socket(daemon, Role::Server, None).await };
    let (opened, ()) = tokio::join!(Connection::open(client, &APP, limits), fake.handshake());
    (opened.expect("the handshake succeeds"), fake)
}

const PATIENCE: Duration = Duration::from_secs(10);

impl Fake {
    async fn handshake(&mut self) {
        let hello = self.text().await;
        assert_eq!(hello["type"], "hello");
        let features = json!({ "fileDownloadRanges": true, "fileTransferAck": true, "agentStreamsMode": true });
        self.send_json(&json!({ "type": "status", "payload": { "status": "server_info", "serverId": "fake", "capabilities": {}, "features": features } }))
            .await;
    }

    pub async fn send_json(&mut self, frame: &Value) {
        self.ws.send(Message::text(frame.to_string())).await.expect("the pipe takes the frame");
    }

    pub async fn next(&mut self) -> Message {
        timeout(PATIENCE, self.ws.next()).await.expect("the client sent nothing within the patience").expect("the pipe ended").expect("a frame")
    }

    pub async fn text(&mut self) -> Value {
        match self.next().await {
            Message::Text(text) => serde_json::from_str(text.as_str()).expect("the client sends JSON"),
            other => panic!("expected a text frame, got {other:?}"),
        }
    }

    pub async fn binary(&mut self) -> Vec<u8> {
        match self.next().await {
            Message::Binary(bytes) => bytes.to_vec(),
            other => panic!("expected a binary frame, got {other:?}"),
        }
    }

    /// Reads the upload request, answers it with `reply` (made from the request's id), and returns the request.
    pub async fn answer_upload(&mut self, reply: impl FnOnce(&str) -> Value) -> Value {
        let frame = self.text().await;
        let request = frame["message"].clone();
        assert_eq!(request["type"], "file_upload_request");
        let id = request["requestId"].as_str().expect("a request has an id").to_owned();
        self.send_json(&json!({ "type": "session", "message": reply(&id) })).await;
        request
    }

    pub async fn accept_upload(&mut self, stream: u8) -> Value {
        self.answer_upload(|id| json!({ "type": "file_upload_response", "requestId": id, "ok": true, "stream": stream })).await
    }

    pub async fn complete(&mut self, transfer_id: &str, stream: u8, ok: bool, bytes_written: u64) {
        self.send_json(&json!({ "type": "session", "message": { "type": "file_upload_complete", "transferId": transfer_id, "stream": stream, "ok": ok, "bytesWritten": bytes_written } })).await;
    }
}

