#!/usr/bin/env node
// Builds the single binary of one target: `npm run build:binary -- --target linux-x64`
// (swe/architecture/single-binary-daemon.md § The build). Needs `npm run build` first (the CLI's
// compiled `dist/` and the web UI); uses the Bun pinned in the root package.json.
//
//   dist-binary/pi-studio-<version>-<target>/       the version folder (S4 of the feature spec)
//     pi-studio                                       the executable: CLI, daemon, relay, Pi, skills
//     bun                                             `#!/bin/sh` script: the same executable as Bun
//     package.json README.md CHANGELOG.md docs/ theme/ assets/ export-html/ photon_rs_bg.wasm
//                                                     what Pi reads from the executable's folder
//     web/                                            packages/web-client/dist/web, for `pi-studio ui`
//   dist-binary/pi-studio-<version>-<target>.tar.gz
//
// Two flags exist for the live checks (scripts/binary-update-check/), never for a release:
//   --version <x.y.z>   the executable reports that version (`--version`, `/api/health`) and the
//                       folder is named after it; the sources and package.json stay as they are
//   --out-dir <dir>     write <dir>/pi-studio-<version>-<target>[.tar.gz] instead of dist-binary/
//
// Cross-compiling works from any host (Bun downloads the target's runtime); `codesign --force -s -` (A10)
// runs only on a macOS host, so a darwin binary built elsewhere is unsigned and must not be shipped.
import { execFileSync } from "node:child_process";
import {
  chmodSync,
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Release target name → Bun's `--target`. */
export const TARGETS = {
  "linux-x64": "bun-linux-x64",
  "linux-arm64": "bun-linux-arm64",
  "darwin-arm64": "bun-darwin-arm64",
  "darwin-x64": "bun-darwin-x64",
};

/** Pi's worker files: `new Worker(...)` targets the bundler cannot see, so they are extra entries. */
const PI_WORKERS = ["dist/utils/image-resize-worker.js", "dist/extensions/codemode/worker.js"];

/** The `bun` script: the executable started as Bun itself (`BUN_BE_BUN`), for Pi's package manager. */
export const BUN_SCRIPT = '#!/bin/sh\nBUN_BE_BUN=1 exec "$(dirname "$0")/pi-studio" "$@"\n';

const PLAIN_VERSION = /^\d+\.\d+\.\d+$/;

const FLAGS = { "--target": "target", "--version": "version", "--out-dir": "outDir" };

/**
 * `{ target }` from `--target <target>` / `--target=<target>`, plus `version` and `outDir` when
 * `--version` / `--out-dir` are given (both spellings); throws on anything else.
 */
export function parseArgs(argv) {
  const values = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const eq = arg.indexOf("=");
    const flag = eq === -1 ? arg : arg.slice(0, eq);
    if (!Object.hasOwn(FLAGS, flag)) throw new Error(`unknown argument: ${arg}`);
    const value = eq === -1 ? argv[++i] : arg.slice(eq + 1);
    if (value === undefined) throw new Error(`${flag} needs a value`);
    values[FLAGS[flag]] = value;
  }
  const { target, version, outDir } = values;
  if (target === undefined) {
    throw new Error(`--target is required (${Object.keys(TARGETS).join(", ")})`);
  }
  if (!Object.hasOwn(TARGETS, target)) {
    throw new Error(`unknown target "${target}" (${Object.keys(TARGETS).join(", ")})`);
  }
  if (version !== undefined && !PLAIN_VERSION.test(version)) {
    throw new Error(`--version "${version}" is not <major>.<minor>.<patch>`);
  }
  return {
    target,
    ...(version !== undefined ? { version } : {}),
    ...(outDir !== undefined ? { outDir } : {}),
  };
}

/** The compiled packages whose `dist/version.generated.js` Bun bundles as the executable's version. */
const VERSIONED_PACKAGES = ["server", "cli", "relay"];

/** The compiled `version.generated.js` of `version` (tsc's output of `gen-version.mjs`' module). */
export function versionModule(version) {
  return `// Generated by scripts/gen-version.mjs from package.json — do not edit.\nexport const PACKAGE_VERSION = ${JSON.stringify(version)};\n`;
}

/**
 * Runs `fn` while the three packages' compiled version modules under `root` say `version`, then
 * puts every file back byte for byte, also when `fn` throws: the checkout's `dist/` is never left
 * relabelled.
 */
export function withVersion(root, version, fn) {
  const files = VERSIONED_PACKAGES.map((name) =>
    join(root, "packages", name, "dist", "version.generated.js"),
  );
  const originals = files.map((file) => readFileSync(file));
  try {
    for (const file of files) writeFileSync(file, versionModule(version));
    return fn();
  } finally {
    files.forEach((file, i) => writeFileSync(file, originals[i]));
  }
}

/** The version folder's name; the archive is `<name>.tar.gz`. */
export function folderName(version, target) {
  return `pi-studio-${version}-${target}`;
}

/**
 * `codesign`'s arguments for the ad-hoc signature of a darwin executable. `--force`: Bun's compile
 * already signs some darwin builds (darwin-x64 on a macos-15-intel runner), and plain
 * `codesign -s -` then fails with "is already signed".
 */
export function codesignArgs(executable) {
  return ["--force", "-s", "-", executable];
}

/**
 * What Pi reads from the executable's folder (`dist/config.js`, `isBunBinary`): `from` is an
 * absolute path (the wasm lives in Pi's or the hoisted `node_modules`), `to` is relative to the
 * version folder. Folders are copied whole.
 */
export function piAssets(piDir, photonWasm) {
  const files = (dir, ext, to) =>
    readdirSync(join(piDir, dir))
      .filter((name) => name.endsWith(ext))
      .map((name) => ({ from: join(piDir, dir, name), to: join(to, name) }));
  return [
    ...["package.json", "README.md", "CHANGELOG.md"].map((name) => ({
      from: join(piDir, name),
      to: name,
    })),
    { from: join(piDir, "docs"), to: "docs" },
    ...files("dist/modes/interactive/theme", ".json", "theme"),
    ...files("dist/modes/interactive/assets", ".png", "assets"),
    { from: join(piDir, "dist/core/export-html/template.html"), to: "export-html/template.html" },
    { from: join(piDir, "dist/core/export-html/template.css"), to: "export-html/template.css" },
    ...files("dist/core/export-html/vendor", ".js", "export-html/vendor"),
    { from: photonWasm, to: "photon_rs_bg.wasm" },
  ];
}

/** The first existing path of `candidates`; throws naming them all otherwise. */
function firstExisting(candidates) {
  const found = candidates.find((path) => existsSync(path));
  if (found === undefined) throw new Error(`not found: ${candidates.join(" | ")}`);
  return found;
}

function folderBytes(dir) {
  let total = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    total += entry.isDirectory() ? folderBytes(path) : statSync(path).size;
  }
  return total;
}

const mib = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MiB`;

function build({ target, version: override, outDir: outBase }) {
  const cli = JSON.parse(readFileSync(join(ROOT, "packages/cli/package.json"), "utf8"));
  const entry = join(ROOT, "packages/cli/dist/binary-main.js");
  const webDist = join(ROOT, "packages/web-client/dist/web");
  const piDir = join(ROOT, "node_modules/@earendil-works/pi-coding-agent");
  if (!existsSync(entry)) throw new Error(`${entry} is missing: run \`npm run build\` first`);
  if (!existsSync(join(webDist, "index.html"))) {
    throw new Error(`${webDist} has no built UI: run \`npm run build\` first`);
  }
  const photonWasm = firstExisting([
    join(piDir, "node_modules/@silvia-odwyer/photon-node/photon_rs_bg.wasm"),
    join(ROOT, "node_modules/@silvia-odwyer/photon-node/photon_rs_bg.wasm"),
  ]);

  const version = override ?? cli.version;
  const name = folderName(version, target);
  const outDir = join(outBase === undefined ? join(ROOT, "dist-binary") : resolve(outBase), name);
  const archive = `${outDir}.tar.gz`;
  rmSync(outDir, { recursive: true, force: true });
  rmSync(archive, { force: true });
  mkdirSync(outDir, { recursive: true });

  console.log(`== compile ${target} (${TARGETS[target]})`);
  const compile = () =>
    execFileSync(
      join(ROOT, "node_modules/.bin/bun"),
      [
        "build",
        "--compile",
        "--no-compile-autoload-bunfig",
        "--no-compile-autoload-dotenv",
        `--target=${TARGETS[target]}`,
        "--define",
        "PI_STUDIO_BINARY=true",
        // `terminal/pty-backend.ts` imports it behind `isBunRuntime()`: never loaded under Bun, and
        // the bundler must not follow it into a native addon.
        "--external",
        "node-pty",
        entry,
        ...PI_WORKERS.map((worker) => join(piDir, worker)),
        "--outfile",
        join(outDir, "pi-studio"),
      ],
      { cwd: ROOT, stdio: "inherit" },
    );
  if (override === undefined) {
    compile();
  } else {
    console.log(`== version ${version} (the sources say ${cli.version})`);
    withVersion(ROOT, version, compile);
  }

  console.log("== assemble");
  for (const { from, to } of piAssets(piDir, photonWasm)) {
    mkdirSync(dirname(join(outDir, to)), { recursive: true });
    cpSync(from, join(outDir, to), { recursive: true });
  }
  cpSync(webDist, join(outDir, "web"), { recursive: true });
  writeFileSync(join(outDir, "bun"), BUN_SCRIPT);
  chmodSync(join(outDir, "bun"), 0o755);
  chmodSync(join(outDir, "pi-studio"), 0o755);

  if (target.startsWith("darwin-")) {
    if (process.platform === "darwin") {
      console.log("== codesign (ad hoc)");
      execFileSync("codesign", codesignArgs(join(outDir, "pi-studio")), { stdio: "inherit" });
    } else {
      console.log("== NOT signed: codesign runs on a macOS host only; do not ship this build");
    }
  }

  console.log("== archive");
  execFileSync("tar", ["-czf", archive, "-C", dirname(outDir), name], { stdio: "inherit" });
  console.log(`folder:  ${outDir} (${mib(folderBytes(outDir))} unpacked)`);
  console.log(`archive: ${archive} (${mib(statSync(archive).size)})`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    build(parseArgs(process.argv.slice(2)));
  } catch (error) {
    console.error(`build-binary: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
